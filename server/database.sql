-- Hextris 排行榜数据库初始化脚本

-- 创建数据库
CREATE DATABASE IF NOT EXISTS hextris_rankings CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

USE hextris_rankings;

-- 创建玩家表
CREATE TABLE IF NOT EXISTS players (
    id INT AUTO_INCREMENT PRIMARY KEY,
    nickname VARCHAR(50) NOT NULL DEFAULT '匿名玩家',
    ip_address VARCHAR(45) NOT NULL,
    region VARCHAR(20) NOT NULL,
    score INT NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    INDEX idx_region (region),
    INDEX idx_score (score DESC),
    INDEX idx_nickname (nickname)
);

-- 创建区域IP范围表
CREATE TABLE IF NOT EXISTS regions (
    id INT AUTO_INCREMENT PRIMARY KEY,
    region_name VARCHAR(20) NOT NULL,
    ip_range_start VARCHAR(45) NOT NULL,
    ip_range_end VARCHAR(45) NOT NULL,
    UNIQUE KEY idx_ip_range (ip_range_start, ip_range_end)
);

